// LocalStorage helpers
export const storageService = {
  getCompany: (): CompanyProfile => {
    const data = localStorage.getItem(STORAGE_KEYS.COMPANY);
    return data ? JSON.parse(data) : DEFAULT_COMPANY;
  },
  saveCompany: (company: CompanyProfile) => {
    localStorage.setItem(STORAGE_KEYS.COMPANY, JSON.stringify(company));
  },

  getNumbering: (): NumberingConfig => {
    const data = localStorage.getItem(STORAGE_KEYS.NUMBERING);
    return data ? JSON.parse(data) : DEFAULT_NUMBERING;
  },
  saveNumbering: (config: NumberingConfig) => {
    localStorage.setItem(STORAGE_KEYS.NUMBERING, JSON.stringify(config));
  },

  getCustomers: (): Customer[] => {
    const data = localStorage.getItem(STORAGE_KEYS.CUSTOMERS);
    return data ? JSON.parse(data) : SEED_CUSTOMERS;
  },
  saveCustomers: (customers: Customer[]) => {
    localStorage.setItem(STORAGE_KEYS.CUSTOMERS, JSON.stringify(customers));
  },

  getProjects: (): Project[] => {
    const data = localStorage.getItem(STORAGE_KEYS.PROJECTS);
    return data ? JSON.parse(data) : SEED_PROJECTS;
  },
  saveProjects: (projects: Project[]) => {
    localStorage.setItem(STORAGE_KEYS.PROJECTS, JSON.stringify(projects));
  },

  getChallans: (): DeliveryChallan[] => {
    const data = localStorage.getItem(STORAGE_KEYS.CHALLANS);
    return data ? JSON.parse(data) : SEED_CHALLANS;
  },
  saveChallans: (challans: DeliveryChallan[]) => {
    localStorage.setItem(STORAGE_KEYS.CHALLANS, JSON.stringify(challans));
  },

  getReports: (): ServiceReport[] => {
    const data = localStorage.getItem(STORAGE_KEYS.REPORTS);
    return data ? JSON.parse(data) : SEED_REPORTS;
  },
  saveReports: (reports: ServiceReport[]) => {
    localStorage.setItem(STORAGE_KEYS.REPORTS, JSON.stringify(reports));
  },

  getInvoices: (): ServiceInvoice[] => {
    const data = localStorage.getItem(STORAGE_KEYS.INVOICES);
    return data ? JSON.parse(data) : SEED_INVOICES;
  },
  saveInvoices: (invoices: ServiceInvoice[]) => {
    localStorage.setItem(STORAGE_KEYS.INVOICES, JSON.stringify(invoices));
  },

  getPayments: (): PaymentReceipt[] => {
    const data = localStorage.getItem(STORAGE_KEYS.PAYMENTS);
    return data ? JSON.parse(data) : SEED_PAYMENTS;
  },
  savePayments: (payments: PaymentReceipt[]) => {
    localStorage.setItem(STORAGE_KEYS.PAYMENTS, JSON.stringify(payments));
  },

  getLedger: (): LedgerEntry[] => {
    const data = localStorage.getItem(STORAGE_KEYS.LEDGER);
    return data ? JSON.parse(data) : SEED_LEDGER;
  },
  saveLedger: (ledger: LedgerEntry[]) => {
    localStorage.setItem(STORAGE_KEYS.LEDGER, JSON.stringify(ledger));
  },

  getCurrentRole: (): string => {
    return localStorage.getItem(STORAGE_KEYS.CURRENT_ROLE) || 'Admin';
  },
  saveCurrentRole: (role: string) => {
    localStorage.setItem(STORAGE_KEYS.CURRENT_ROLE, role);
  },

  resetAllData: () => {
    localStorage.setItem(STORAGE_KEYS.COMPANY, JSON.stringify(DEFAULT_COMPANY));
    localStorage.setItem(STORAGE_KEYS.NUMBERING, JSON.stringify(DEFAULT_NUMBERING));
    localStorage.setItem(STORAGE_KEYS.CUSTOMERS, JSON.stringify(SEED_CUSTOMERS));
    localStorage.setItem(STORAGE_KEYS.PROJECTS, JSON.stringify(SEED_PROJECTS));
    localStorage.setItem(STORAGE_KEYS.CHALLANS, JSON.stringify(SEED_CHALLANS));
    localStorage.setItem(STORAGE_KEYS.REPORTS, JSON.stringify(SEED_REPORTS));
    localStorage.setItem(STORAGE_KEYS.INVOICES, JSON.stringify(SEED_INVOICES));
    localStorage.setItem(STORAGE_KEYS.PAYMENTS, JSON.stringify(SEED_PAYMENTS));
    localStorage.setItem(STORAGE_KEYS.LEDGER, JSON.stringify(SEED_LEDGER));
    localStorage.setItem(STORAGE_KEYS.CURRENT_ROLE, 'Admin');
  },

  exportBackup: () => {
    const backup = {
      company: storageService.getCompany(),
      numbering: storageService.getNumbering(),
      customers: storageService.getCustomers(),
      projects: storageService.getProjects(),
      challans: storageService.getChallans(),
      reports: storageService.getReports(),
      invoices: storageService.getInvoices(),
      payments: storageService.getPayments(),
      ledger: storageService.getLedger(),
      exportedAt: new Date().toISOString(),
    };
    return JSON.stringify(backup, null, 2);
  },

  importBackup: (jsonStr: string): boolean => {
    try {
      const data = JSON.parse(jsonStr);
      if (data.company) storageService.saveCompany(data.company);
      if (data.numbering) storageService.saveNumbering(data.numbering);
      if (data.customers) storageService.saveCustomers(data.customers);
      if (data.projects) storageService.saveProjects(data.projects);
      if (data.challans) storageService.saveChallans(data.challans);
      if (data.reports) storageService.saveReports(data.reports);
      if (data.invoices) storageService.saveInvoices(data.invoices);
      if (data.payments) storageService.savePayments(data.payments);
      if (data.ledger) storageService.saveLedger(data.ledger);
      return true;
    } catch (e) {
      console.error('Failed to import backup:', e);
      return false;
    }
  },
};
